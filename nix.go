// These are vars (not consts) so tests can point them at a temp directory.
var (
	nixosDir    = "/etc/nixos"
	sidecarPath = nixosDir + "/nasty-config.nix"
	mainConfig  = nixosDir + "/configuration.nix"
	flakePath   = nixosDir + "/flake.nix"
)

// validPkgRegex accepts valid Nix attribute paths only, e.g. "firefox" or
// "python3Packages.requests". It rejects leading digits/dashes and anything
// that could break out of the generated Nix list.
var validPkgRegex = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_'-]*(\.[A-Za-z_][A-Za-z0-9_'-]*)*$`)

type HardwareToggles struct {
	Bluetooth bool
	Printing  bool
	Avahi     bool
}

type SystemState struct {
	Packages []string
	Hardware HardwareToggles
}

// lib.mkDefault means anything you set yourself in configuration.nix wins over
// these values, so the app can never silently switch off a service you
// configured by hand.
var sidecarTmpl = template.Must(template.New("sidecar").Parse(`# This file is auto-generated by NASTY.
# DO NOT EDIT MANUALLY. Any changes will be overwritten.
# Ensure your configuration.nix includes: imports = [ ./nasty-config.nix ];

{ config, lib, pkgs, ... }:

{
  environment.systemPackages = with pkgs; [
    {{- range .Packages }}
    {{ . }}
    {{- end }}
  ];

  hardware.bluetooth.enable = lib.mkDefault {{ if .Hardware.Bluetooth }}true{{ else }}false{{ end }};
  services.printing.enable = lib.mkDefault {{ if .Hardware.Printing }}true{{ else }}false{{ end }};
  services.avahi.enable = lib.mkDefault {{ if .Hardware.Avahi }}true{{ else }}false{{ end }};
}
`))

func uniqueSorted(in []string) []string {
	seen := make(map[string]bool, len(in))
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	sort.Strings(out)
	return out
}

// sanitizeState drops invalid package names and de-duplicates the rest.
func sanitizeState(st SystemState) (SystemState, []string) {
	var valid, dropped []string
	for _, p := range st.Packages {
		if validPkgRegex.MatchString(p) {
			valid = append(valid, p)
		} else {
			dropped = append(dropped, p)
		}
	}
	st.Packages = uniqueSorted(valid)
	return st, dropped
}

// renderSidecar renders the module. Output is deterministic for a given state.
func renderSidecar(state SystemState) ([]byte, error) {
	state.Packages = uniqueSorted(state.Packages)
	var buf bytes.Buffer
	if err := sidecarTmpl.Execute(&buf, state); err != nil {
		return nil, fmt.Errorf("failed to render config: %w", err)
	}
	return buf.Bytes(), nil
}

// setupWarnings reports setups where the sidecar would be silently ignored.
func setupWarnings() []string {
	var warns []string

	data, err := os.ReadFile(mainConfig)
	if err != nil {
		warns = append(warns, fmt.Sprintf("Could not read %s to check the import: %v", mainConfig, err))
	} else if !strings.Contains(string(data), "nasty-config.nix") {
		warns = append(warns, "configuration.nix does not import nasty-config.nix. Add  imports = [ ./nasty-config.nix ];  or your changes will be ignored.")
	}

	if _, err := os.Stat(flakePath); err == nil {
		warns = append(warns, "A flake.nix was found. Flake systems need the sidecar to be git-tracked and rebuilt with --flake; NASTY runs a plain nixos-rebuild.")
	}
	return warns
}

// ---- diff -------------------------------------------------------------------

// StateDiff is a friendly summary of what changed between two states.
type StateDiff struct {
	Added    []string
	Removed  []string
	Hardware []string
}

func (d StateDiff) Count() int { return len(d.Added) + len(d.Removed) + len(d.Hardware) }

func onOff(b bool) string {
	if b {
		return "on"
	}
	return "off"
}

func diffStates(oldS, newS SystemState) StateDiff {
	var d StateDiff

	oldSet := make(map[string]bool, len(oldS.Packages))
	for _, p := range oldS.Packages {
		oldSet[p] = true
	}
	newSet := make(map[string]bool, len(newS.Packages))
	for _, p := range newS.Packages {
		newSet[p] = true
	}
	for p := range newSet {
		if !oldSet[p] {
			d.Added = append(d.Added, p)
		}
	}
	for p := range oldSet {
		if !newSet[p] {
			d.Removed = append(d.Removed, p)
		}
	}
	sort.Strings(d.Added)
	sort.Strings(d.Removed)

	for _, h := range []struct {
		name string
		a, b bool
	}{
		{"Bluetooth", oldS.Hardware.Bluetooth, newS.Hardware.Bluetooth},
		{"Printing (CUPS)", oldS.Hardware.Printing, newS.Hardware.Printing},
		{"Avahi discovery", oldS.Hardware.Avahi, newS.Hardware.Avahi},
	} {
		if h.a != h.b {
			d.Hardware = append(d.Hardware, fmt.Sprintf("%s: %s -> %s", h.name, onOff(h.a), onOff(h.b)))
		}
	}
	return d
}

// DiffLine is one changed line: Kind is '+' (added), '-' (removed) or '~' (note).
type DiffLine struct {
	Kind byte
	Text string
}

func splitLines(s string) []string {
	if s == "" {
		return nil
	}
	return strings.Split(strings.TrimRight(s, "\n"), "\n")
}

// lineDiff returns only the changed lines, using a longest-common-subsequence
// table. Config files are small, so the O(n*m) cost is fine.
func lineDiff(a, b []string) []DiffLine {
	n, m := len(a), len(b)
	if n*m > 4_000_000 {
		return []DiffLine{{Kind: '~', Text: "(file too large to show a line diff)"}}
	}

	dp := make([][]int, n+1)
	for i := range dp {
		dp[i] = make([]int, m+1)
	}
	for i := n - 1; i >= 0; i-- {
		for j := m - 1; j >= 0; j-- {
			switch {
			case a[i] == b[j]:
				dp[i][j] = dp[i+1][j+1] + 1
			case dp[i+1][j] >= dp[i][j+1]:
				dp[i][j] = dp[i+1][j]
			default:
				dp[i][j] = dp[i][j+1]
			}
		}
	}

	var out []DiffLine
	i, j := 0, 0
	for i < n && j < m {
		switch {
		case a[i] == b[j]:
			i++
			j++
		case dp[i+1][j] >= dp[i][j+1]:
			out = append(out, DiffLine{'-', a[i]})
			i++
		default:
			out = append(out, DiffLine{'+', b[j]})
			j++
		}
	}
	for ; i < n; i++ {
		out = append(out, DiffLine{'-', a[i]})
	}
	for ; j < m; j++ {
		out = append(out, DiffLine{'+', b[j]})
	}
	return out
}

// ---- generations ------------------------------------------------------------

type Generation struct {
	Number  int
	Date    time.Time
	Version string
	Current bool
	Path    string
}

var genRe = regexp.MustCompile(`^system-(\d+)-link$`)

// listGenerationsIn reads <dir>/system-N-link symlinks (newest first).
func listGenerationsIn(dir string) ([]Generation, error) {
	links, err := filepath.Glob(filepath.Join(dir, "system-*-link"))
	if err != nil {
		return nil, err
	}
	current, _ := os.Readlink(filepath.Join(dir, "system"))
	current = filepath.Base(current)

	var gens []Generation
	for _, l := range links {
		m := genRe.FindStringSubmatch(filepath.Base(l))
		if m == nil {
			continue
		}
		n, _ := strconv.Atoi(m[1])
		g := Generation{Number: n, Path: l, Current: filepath.Base(l) == current}
		if fi, err := os.Lstat(l); err == nil {
			g.Date = fi.ModTime()
		}
		if b, err := os.ReadFile(filepath.Join(l, "nixos-version")); err == nil {
			g.Version = strings.TrimSpace(string(b))
		}
		gens = append(gens, g)
	}
	sort.Slice(gens, func(i, j int) bool { return gens[i].Number > gens[j].Number })
	return gens, nil
}

func listGenerations() ([]Generation, error) {
	return listGenerationsIn("/nix/var/nix/profiles")
}

// previousGeneration returns the generation just older than the current one.
func previousGeneration(gens []Generation) (Generation, bool) {
	for i, g := range gens {
		if g.Current && i+1 < len(gens) {
			return gens[i+1], true
		}
	}
	return Generation{}, false
}
